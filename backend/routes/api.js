const express = require('express')
const { createResourceRouter } = require('./resourceRoutes')
const { createSubjectRouter } = require('./subjects')
const { createHabitRouter } = require('./habits')
const { createStudySessionRouter } = require('./studySessions')
const { createKnowledgeRouter, createTopicKnowledgeRouter } = require('./knowledge')
const { createRevisionRouter } = require('./revisions')
const { createAnalyticsRouter } = require('./analytics')
const { createAssessmentRouter } = require('./assessments')
const { createRecoveryRouter } = require('./recovery')
const { createForecastRouter } = require('./forecast')
const { createDashboardRouter } = require('./dashboard')

function createApiRouter(db) {
  const router = express.Router()
  router.get('/health', (req, res) => res.json({ data: { status: 'ok', database: 'connected' } }))
  router.use('/dashboard', createDashboardRouter(db))
  router.use('/analytics', createAnalyticsRouter(db))
  router.use('/recovery', createRecoveryRouter(db))
  router.use('/forecast', createForecastRouter(db))
  router.use('/knowledge', createKnowledgeRouter(db))
  router.use('/topics', createTopicKnowledgeRouter(db))
  router.use('/subjects', createSubjectRouter(db))
  router.use('/subjects', createResourceRouter(db, 'subjects'))
  router.use('/units', createResourceRouter(db, 'units'))
  router.use('/topics', createResourceRouter(db, 'topics'))
  router.use('/habits', createHabitRouter(db))
  router.use('/habits', createResourceRouter(db, 'habits'))
  router.use('/habit-logs', createResourceRouter(db, 'habit_logs'))
  router.use('/study-plans', createResourceRouter(db, 'study_plans'))
  router.use('/study-sessions', createStudySessionRouter(db))
  router.use('/study-sessions', createResourceRouter(db, 'study_sessions'))
  router.use('/topic-assessments', createAssessmentRouter(db))
  router.use('/revision-tasks', createRevisionRouter(db))
  router.use('/revision-tasks', createResourceRouter(db, 'revision_tasks'))
  return router
}

module.exports = { createApiRouter }
